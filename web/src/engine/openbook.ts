export function openingMove(pos: Position): number {
  if (pos.pending >= 0) return -1;
  let stones = 0;
  let black = -1;
  for (let i = 0; i < SIZE; i++) {
    if (pos.board[i] !== EMPTY) {
      stones++;
      if (pos.board[i] === BLACK) black = i;
    }
  }
  if (stones === 0) return FIRST;
  if (stones === 1 && black >= 0) return REPLY[black];
  return -1;
}
